function getLang() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    return stored && UI_STRINGS[stored] ? stored : "en";
  } catch (e) {
    return "en";
  }
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  window.location.reload();
}

function t(key) {
  const lang = getLang();
  return (UI_STRINGS[lang] && UI_STRINGS[lang][key]) || UI_STRINGS.en[key] || key;
}

function localizedName(product) {
  const lang = getLang();
  return product["name_" + lang] || product.name;
}

function localizedDesc(product) {
  const lang = getLang();
  return product["desc_" + lang] || product.desc;
}

function localizedLong(product) {
  const lang = getLang();
  return product["long_" + lang] || product.long;
}

function localizedCategoryName(category) {
  const lang = getLang();
  return category["name_" + lang] || category.name;
}

function localizedCondition(product) {
  if (!product.condition) return "";
  const lang = getLang();
  return (product["condition_" + lang]) || product.condition;
}

function applyStaticTranslations(root) {
  (root || document).querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  (root || document).querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}
